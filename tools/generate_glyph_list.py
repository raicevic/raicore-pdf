"""Generates src/RaiCore.Pdf.Extraction/Fonts/GlyphList.g.cs and Encodings.g.cs.

Text extraction maps the glyph names of simple fonts (from /Differences or a font's built-in encoding) to Unicode
with the Adobe Glyph List, and needs the base encodings of ISO 32000-2 Annex D as code -> Unicode tables:

- GlyphList.g.cs: the Adobe Glyph List (glyphlist.txt, BSD-3-Clause, Adobe), as fontTools ships it.
- Encodings.g.cs: StandardEncoding (glyph names from fontTools, mapped through the AGL) and MacRomanEncoding (Python's
  mac_roman codec, with the PDF table's differences: 0xDB is currency, not the euro, and the control codes, 0x7F and
  the Apple logo are undefined). WinAnsiEncoding comes from the core (RaiCore.Pdf.Fonts.WinAnsiEncoding).

Usage: python tools/generate_glyph_list.py   (needs fontTools)
"""
from pathlib import Path

from fontTools import agl
from fontTools.encodings.StandardEncoding import StandardEncoding

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "RaiCore.Pdf.Extraction" / "Fonts"

HEADER = """// <auto-generated>
// Generated by tools/generate_glyph_list.py{source}.
// Do not edit by hand.
// </auto-generated>

#nullable enable

namespace RaiCore.Pdf.Extraction.Fonts;
"""


def escape(text):
    return "".join(c if 0x20 <= ord(c) < 0x7F and c not in '\\"' else "\\u%04X" % ord(c) for c in text)


def glyph_list():
    lines = []
    for name in sorted(agl.LEGACY_AGL2UV):
        code_points = agl.LEGACY_AGL2UV[name]
        lines.append(name + " " + " ".join("%04X" % c for c in code_points))
    body = "\n".join(lines)
    return (HEADER.format(source=" from the Adobe Glyph List (glyphlist.txt, BSD-3-Clause, Adobe; see THIRD-PARTY-NOTICES.md)")
            + "\ninternal static partial class GlyphNames\n{\n"
            + "    /// <summary>The Adobe Glyph List: one glyph per line, its name and the code points it stands for (hex).</summary>\n"
            + '    private const string AdobeGlyphList = """\n' + body + '\n""";\n}\n')


def table(chars):
    assert len(chars) == 256
    rows = []
    for start in range(0, 256, 16):
        rows.append('        "' + escape("".join(chars[start:start + 16])) + '"')
    return " +\n".join(rows)


def encodings():
    standard = []
    for name in StandardEncoding:
        code_points = agl.LEGACY_AGL2UV.get(name)
        standard.append("\0" if name == ".notdef" or not code_points else chr(code_points[0]))

    mac = []
    for code in range(256):
        if code < 0x20 or code in (0x7F, 0xF0):
            mac.append("\0")
        elif code == 0xDB:
            mac.append(chr(0xA4))
        else:
            mac.append(bytes([code]).decode("mac_roman"))

    return (HEADER.format(source=" (StandardEncoding from fontTools and the Adobe Glyph List, MacRomanEncoding from Python's mac_roman codec)")
            + "\ninternal static partial class SimpleEncodings\n{\n"
            + "    /// <summary>StandardEncoding (ISO 32000-2, Annex D): the character of each code, <c>\\0</c> where undefined.</summary>\n"
            + "    private const string StandardTable =\n" + table(standard) + ";\n\n"
            + "    /// <summary>MacRomanEncoding (ISO 32000-2, Annex D): the character of each code, <c>\\0</c> where undefined.</summary>\n"
            + "    private const string MacRomanTable =\n" + table(mac) + ";\n}\n")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "GlyphList.g.cs").write_text(glyph_list(), encoding="ascii")
    (OUT / "Encodings.g.cs").write_text(encodings(), encoding="ascii")


if __name__ == "__main__":
    main()
