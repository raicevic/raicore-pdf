"""Generates src/RaiCore.Pdf.Layout/Text/LineBreakData.g.cs from the Unicode Character Database.

Each code point gets a packed 16-bit value: the Line_Break class (bits 0-5) plus the extra properties that
UAX #14 rules consult: East Asian width F/W/H (bit 6), Extended_Pictographic (bit 7), General_Category
Mn or Mc (bit 8), Pi (bit 9), Pf (bit 10) and Cn (bit 11).

Usage: python tools/generate_line_break_data.py <dir with LineBreak.txt, EastAsianWidth.txt,
       emoji-data.txt, DerivedGeneralCategory.txt>   (files from https://www.unicode.org/Public/UCD/latest/)
"""
import re
import sys
from pathlib import Path

# Order must match the LineBreakClass enum in LineBreaker.cs.
CLASSES = [
    "XX", "BK", "CR", "LF", "NL", "SP", "ZW", "WJ", "GL", "CM", "ZWJ", "CB", "BA", "BB", "B2", "HY", "HH",
    "CL", "CP", "EX", "IN", "NS", "OP", "QU", "IS", "NU", "PO", "PR", "SY", "AI", "AK", "AL", "AP", "AS",
    "CJ", "EB", "EM", "H2", "H3", "HL", "ID", "JL", "JV", "JT", "RI", "SA", "SG", "VF", "VI",
]
MAX = 0x110000


def read_ranges(path, field_filter=None):
    """Yields (start, end, value) from a UCD file of the form 'XXXX..YYYY ; Value # comment'."""
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        cps, value = [p.strip() for p in line.split(";")[:2]]
        start, _, end = cps.partition("..")
        start = int(start, 16)
        end = int(end, 16) if end else start
        if field_filter is None or value == field_filter:
            yield start, end, value


def version(path):
    first = Path(path).read_text(encoding="utf-8").splitlines()[0]
    m = re.search(r"(\d+\.\d+\.\d+)", first)
    return m.group(1) if m else "?"


def main(ucd):
    ucd = Path(ucd)
    lb = bytearray([CLASSES.index("XX")]) * MAX
    for s, e, v in read_ranges(ucd / "LineBreak.txt"):
        lb[s:e + 1] = bytes([CLASSES.index(v)]) * (e - s + 1)

    flags = [0] * MAX
    for s, e, v in read_ranges(ucd / "EastAsianWidth.txt"):
        if v in ("F", "W", "H"):
            for c in range(s, e + 1):
                flags[c] |= 1 << 6
    for s, e, _ in read_ranges(ucd / "emoji-data.txt", "Extended_Pictographic"):
        for c in range(s, e + 1):
            flags[c] |= 1 << 7
    assigned = bytearray(MAX)
    for s, e, v in read_ranges(ucd / "DerivedGeneralCategory.txt"):
        bit = {"Mn": 8, "Mc": 8, "Pi": 9, "Pf": 10}.get(v)
        for c in range(s, e + 1):
            if v != "Cn":
                assigned[c] = 1
            if bit:
                flags[c] |= 1 << bit
    for c in range(MAX):
        if not assigned[c]:
            flags[c] |= 1 << 11

    values = [lb[c] | flags[c] for c in range(MAX)]
    starts, packed = [], []
    for c in range(MAX):
        if c == 0 or values[c] != values[c - 1]:
            starts.append(c)
            packed.append(values[c])

    def chunks(items, width=16):
        for i in range(0, len(items), width):
            yield ", ".join(str(x) for x in items[i:i + width])

    out = [
        "// <auto-generated>",
        f"// Generated by tools/generate_line_break_data.py from the Unicode Character Database {version(ucd / 'LineBreak.txt')}.",
        "// Do not edit by hand.",
        "// </auto-generated>",
        "",
        "#nullable enable",
        "",
        "namespace RaiCore.Pdf.Layout.Text;",
        "",
        "internal static partial class LineBreakData",
        "{",
        f"    public const string UnicodeVersion = \"{version(ucd / 'LineBreak.txt')}\";",
        "",
        f"    /// <summary>First code point of each of the {len(starts)} ranges, ascending.</summary>",
        "    private static ReadOnlySpan<int> RangeStarts =>",
        "    [",
        *[f"        {c}," for c in chunks(starts)],
        "    ];",
        "",
        "    /// <summary>Packed properties of each range (see the generator for the bit layout).</summary>",
        "    private static ReadOnlySpan<ushort> RangeValues =>",
        "    [",
        *[f"        {c}," for c in chunks(packed)],
        "    ];",
        "}",
    ]
    target = Path(__file__).resolve().parent.parent / "src/RaiCore.Pdf.Layout/Text/LineBreakData.g.cs"
    target.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {target}: {len(starts)} ranges")


if __name__ == "__main__":
    main(sys.argv[1])
