"""Generates src/RaiCore.Pdf.Layout/Text/BidiData.g.cs from the Unicode Character Database.

Each code point gets its Bidi_Class (the @missing defaults of DerivedBidiClass.txt first, then the listed values),
stored as ranges; paired brackets (BidiBrackets.txt) get their pair and whether they open or close.

Usage: python tools/generate_bidi_data.py <dir with DerivedBidiClass.txt and BidiBrackets.txt>
       (files from https://www.unicode.org/Public/UCD/latest/ucd/, DerivedBidiClass.txt from extracted/)
"""
import re
import sys
from pathlib import Path

# Order must match the BidiClass enum in BidiAlgorithm.cs.
CLASSES = [
    "L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS", "ON",
    "LRE", "LRO", "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI",
]
LONG_NAMES = {
    "Left_To_Right": "L", "Right_To_Left": "R", "Arabic_Letter": "AL", "European_Number": "EN",
    "European_Separator": "ES", "European_Terminator": "ET", "Arabic_Number": "AN", "Common_Separator": "CS",
    "Nonspacing_Mark": "NSM", "Boundary_Neutral": "BN", "Paragraph_Separator": "B", "Segment_Separator": "S",
    "White_Space": "WS", "Other_Neutral": "ON", "Left_To_Right_Embedding": "LRE", "Left_To_Right_Override": "LRO",
    "Right_To_Left_Embedding": "RLE", "Right_To_Left_Override": "RLO", "Pop_Directional_Format": "PDF",
    "Left_To_Right_Isolate": "LRI", "Right_To_Left_Isolate": "RLI", "First_Strong_Isolate": "FSI",
    "Pop_Directional_Isolate": "PDI",
}
MAX = 0x110000


def parse_range(cps):
    start, _, end = cps.strip().partition("..")
    start = int(start, 16)
    return start, int(end, 16) if end else start


def version(path):
    first = Path(path).read_text(encoding="utf-8").splitlines()[0]
    m = re.search(r"(\d+\.\d+\.\d+)", first)
    return m.group(1) if m else "?"


def main(ucd):
    ucd = Path(ucd)
    classes = bytearray(MAX)
    lines = (ucd / "DerivedBidiClass.txt").read_text(encoding="utf-8").splitlines()

    # Defaults for unlisted code points, in file order (later, narrower ranges override the first, global one).
    for line in lines:
        m = re.match(r"#\s*@missing:\s*([0-9A-F.]+)\s*;\s*(\w+)", line)
        if m:
            s, e = parse_range(m.group(1))
            value = CLASSES.index(LONG_NAMES.get(m.group(2), m.group(2)))
            classes[s:e + 1] = bytes([value]) * (e - s + 1)

    for line in lines:
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        cps, value = [p.strip() for p in line.split(";")[:2]]
        s, e = parse_range(cps)
        classes[s:e + 1] = bytes([CLASSES.index(value)]) * (e - s + 1)

    starts, packed = [], []
    for c in range(MAX):
        if c == 0 or classes[c] != classes[c - 1]:
            starts.append(c)
            packed.append(classes[c])

    brackets = []
    for line in (ucd / "BidiBrackets.txt").read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        cp, pair, kind = [p.strip() for p in line.split(";")[:3]]
        brackets.append((int(cp, 16), int(pair, 16), 1 if kind == "o" else 2))
    brackets.sort()

    def chunks(items, width=16):
        for i in range(0, len(items), width):
            yield ", ".join(str(x) for x in items[i:i + width])

    v = version(ucd / "DerivedBidiClass.txt")
    out = [
        "// <auto-generated>",
        f"// Generated by tools/generate_bidi_data.py from the Unicode Character Database {v}.",
        "// Do not edit by hand.",
        "// </auto-generated>",
        "",
        "#nullable enable",
        "",
        "namespace RaiCore.Pdf.Layout.Text;",
        "",
        "internal static partial class BidiData",
        "{",
        f"    public const string UnicodeVersion = \"{v}\";",
        "",
        f"    /// <summary>First code point of each of the {len(starts)} ranges, ascending.</summary>",
        "    private static ReadOnlySpan<int> RangeStarts =>",
        "    [",
        *[f"        {c}," for c in chunks(starts)],
        "    ];",
        "",
        "    /// <summary>The <see cref=\"BidiClass\"/> of each range.</summary>",
        "    private static ReadOnlySpan<byte> RangeClasses =>",
        "    [",
        *[f"        {c}," for c in chunks(packed)],
        "    ];",
        "",
        f"    /// <summary>The {len(brackets)} paired brackets, ascending.</summary>",
        "    private static ReadOnlySpan<int> BracketCodePoints =>",
        "    [",
        *[f"        {c}," for c in chunks([b[0] for b in brackets])],
        "    ];",
        "",
        "    /// <summary>Each bracket's pair.</summary>",
        "    private static ReadOnlySpan<int> BracketPairs =>",
        "    [",
        *[f"        {c}," for c in chunks([b[1] for b in brackets])],
        "    ];",
        "",
        "    /// <summary>Each bracket's <see cref=\"BracketType\"/> (1 opens, 2 closes).</summary>",
        "    private static ReadOnlySpan<byte> BracketKinds =>",
        "    [",
        *[f"        {c}," for c in chunks([b[2] for b in brackets])],
        "    ];",
        "}",
    ]
    target = Path(__file__).resolve().parent.parent / "src/RaiCore.Pdf.Layout/Text/BidiData.g.cs"
    target.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {target}: {len(starts)} ranges, {len(brackets)} brackets")


if __name__ == "__main__":
    main(sys.argv[1])
