"""Generates src/RaiCore.Pdf/Fonts/StandardFontMetrics.g.cs.

The 14 standard PDF fonts are not embedded, so RaiCore.Pdf needs their widths to measure text.
Liberation Sans/Serif/Mono are metric-compatible with Helvetica/Times/Courier, so their advance
widths for each WinAnsiEncoding code are used (scaled to 1000 units per em).

Usage: python tools/generate_standard_font_metrics.py <dir with Liberation*.ttf>   (needs fontTools)
"""
import sys
from pathlib import Path
from fontTools.ttLib import TTFont

FONTS = [
    ("Helvetica", "LiberationSans-Regular"), ("HelveticaBold", "LiberationSans-Bold"),
    ("HelveticaOblique", "LiberationSans-Italic"), ("HelveticaBoldOblique", "LiberationSans-BoldItalic"),
    ("TimesRoman", "LiberationSerif-Regular"), ("TimesBold", "LiberationSerif-Bold"),
    ("TimesItalic", "LiberationSerif-Italic"), ("TimesBoldItalic", "LiberationSerif-BoldItalic"),
    ("Courier", "LiberationMono-Regular"), ("CourierBold", "LiberationMono-Bold"),
    ("CourierOblique", "LiberationMono-Italic"), ("CourierBoldOblique", "LiberationMono-BoldItalic"),
]

def winansi(code):
    if 0x80 <= code <= 0x9F:
        try:
            return bytes([code]).decode("cp1252")
        except UnicodeDecodeError:
            return None
    return chr(code)

def main(font_dir):
    out = [
        "// <auto-generated>",
        "// Generated by tools/generate_standard_font_metrics.py from Liberation Fonts 2.1.5 (SIL OFL 1.1).",
        "// Do not edit by hand.",
        "// </auto-generated>",
        "",
        "#nullable enable",
        "",
        "namespace RaiCore.Pdf.Fonts;",
        "",
        "internal static partial class StandardFontMetrics",
        "{",
        "    private static readonly Metrics?[] All =",
        "    [",
    ]
    for enum_name, file in FONTS:
        font = TTFont(Path(font_dir) / f"{file}.ttf")
        upem = font["head"].unitsPerEm
        cmap = font.getBestCmap()
        hmtx = font["hmtx"]
        scale = 1000 / upem
        question = round(hmtx[cmap[ord("?")]][0] * scale)
        widths = []
        for code in range(256):
            ch = winansi(code)
            if code < 0x20 or ch is None or ord(ch) not in cmap:
                widths.append(question)
            else:
                widths.append(round(hmtx[cmap[ord(ch)]][0] * scale))
        os2, hhea = font["OS/2"], font["hhea"]
        values = ", ".join(str(w) for w in widths)
        out.append(f"        // {enum_name} ({file})")
        out.append(
            f"        new({round(hhea.ascent * scale)}, {round(hhea.descent * scale)}, {round(hhea.lineGap * scale)}, "
            f"{round(os2.sCapHeight * scale)}, {round(os2.sxHeight * scale)}, [{values}]),")
    out.append("        null, // Symbol: no metric-compatible open font yet")
    out.append("        null, // ZapfDingbats")
    out.append("    ];")
    out.append("}")
    target = Path(__file__).resolve().parent.parent / "src/RaiCore.Pdf/Fonts/StandardFontMetrics.g.cs"
    target.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {target}")

if __name__ == "__main__":
    main(sys.argv[1])
