using System.IO.Compression;
using System.Xml.Linq;

namespace RaiCore.Pdf.Sheets.Xlsx;

/// <summary>
/// A pivot table style element's format: what its <c>dxf</c> sets of the font, the fill and the borders, with the inner
/// borders of its region (<c>horizontal</c> between its rows, <c>vertical</c> between its columns).
/// </summary>
internal sealed record PivotStyleFormat(DifferentialFormat Format, CellBorder? Horizontal, CellBorder? Vertical);

/// <summary>
/// The styles of pivot tables: Excel's built-in ones (<c>PivotStyleLight1</c>-<c>28</c>, <c>PivotStyleMedium1</c>-<c>28</c>,
/// <c>PivotStyleDark1</c>-<c>28</c>; ECMA-376's predefined table styles, from Apache POI's <c>presetTableStyles.xml</c>,
/// generated by <c>tools/generate_pivot_styles.py</c>) and a workbook's own (<c>tableStyles</c> in its styles part), each
/// a format for each of its elements (<c>headerRow</c>, <c>totalRow</c>, <c>firstRowSubheading</c>...).
/// </summary>
internal static class PivotStyles
{
    /// <summary>The built-in styles' definitions by name: each a <c>dxfs</c> and a <c>tableStyles</c> element.</summary>
    private static readonly Lazy<Dictionary<string, XElement>> BuiltIn = new(LoadBuiltIn);

    /// <summary>The names of the built-in styles.</summary>
    public static IEnumerable<string> BuiltInNames => BuiltIn.Value.Keys;

    /// <summary>A built-in style's elements in a workbook's colors, or <c>null</c> for a name that is not one.</summary>
    public static Dictionary<string, PivotStyleFormat>? ReadBuiltIn(string name, XlsxColors colors)
    {
        if (!BuiltIn.Value.TryGetValue(name, out var definition))
        {
            return null;
        }

        var style = definition.Elements().FirstOrDefault(e => e.Name.LocalName == "tableStyles")?.Elements().FirstOrDefault(e => e.Name.LocalName == "tableStyle");
        var dxfs = definition.Elements().FirstOrDefault(e => e.Name.LocalName == "dxfs")?.Elements().Where(e => e.Name.LocalName == "dxf").ToList() ?? [];
        return style is null ? null : Read(style, dxfs, colors);
    }

    /// <summary>
    /// A table style's elements (<c>tableStyleElement</c>: its type and the index of its format among
    /// <paramref name="dxfs"/>) in a workbook's colors; elements whose format is missing are left out.
    /// </summary>
    public static Dictionary<string, PivotStyleFormat> Read(XElement tableStyle, IReadOnlyList<XElement> dxfs, XlsxColors colors)
    {
        var elements = new Dictionary<string, PivotStyleFormat>(StringComparer.Ordinal);
        foreach (var element in tableStyle.Elements().Where(e => e.Name.LocalName == "tableStyleElement").Take(64))
        {
            if ((string?)element.Attribute("type") is { } type
                && int.TryParse((string?)element.Attribute("dxfId"), System.Globalization.NumberStyles.None, System.Globalization.CultureInfo.InvariantCulture, out var id)
                && id < dxfs.Count)
            {
                elements[type] = ReadFormat(dxfs[id], colors);
            }
        }

        return elements;
    }

    /// <summary>A <c>dxf</c> of a table style: its format, and the inner borders of its border.</summary>
    internal static PivotStyleFormat ReadFormat(XElement dxf, XlsxColors colors)
    {
        var border = dxf.Elements().FirstOrDefault(e => e.Name.LocalName == "border");
        CellBorder? Inner(string name) => border?.Elements().FirstOrDefault(e => e.Name.LocalName == name) is { } side
            && (string?)side.Attribute("style") is { } style && style != "none"
            ? XlsxStyles.Border(style, side.Elements().FirstOrDefault(e => e.Name.LocalName == "color") is { } c
                ? colors.Resolve((string?)c.Attribute("rgb"), (string?)c.Attribute("indexed"), (string?)c.Attribute("theme"), (string?)c.Attribute("tint"), (string?)c.Attribute("auto"))
                : null)
            : null;
        return new PivotStyleFormat(DifferentialFormat.Read(dxf, colors), Inner("horizontal"), Inner("vertical"));
    }

    private static Dictionary<string, XElement> LoadBuiltIn()
    {
        using var stream = typeof(PivotStyles).Assembly.GetManifestResourceStream("RaiCore.Pdf.Sheets.PivotStyles.xml.gz")
            ?? throw new InvalidOperationException("The built-in pivot styles are missing from the assembly.");
        using var unzipped = new GZipStream(stream, CompressionMode.Decompress);
        var root = XElement.Load(unzipped);
        return root.Elements().ToDictionary(e => e.Name.LocalName, StringComparer.Ordinal);
    }
}
